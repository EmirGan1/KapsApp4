import { createHash } from "node:crypto";
import type { CefrLevel } from "../../shared/germanActivities";

export type PartOfSpeech = "noun" | "verb" | "adj" | "adv" | "phrase" | "sentence";

export interface CurriculumEntry {
  id: string;
  de: string;
  tr: string;
  alternatives?: string[];
  level: CefrLevel;
  topic: string;
  pos: PartOfSpeech;
  article: "" | "der" | "die" | "das";
  plural?: string;
  grammar: string;
  exampleDe: string;
  exampleTr: string;
  conjugation?: {
    pronoun: string;
    tense: string;
    promptDe: string;
    answer: string;
    options: string[];
    explanation: string;
  };
  completion?: {
    stem: string;
    answer: string;
    distractors: string[];
    trHint: string;
    explanation: string;
  };
}

type RawSeed = Omit<CurriculumEntry, "id" | "article"> & {
  article?: "" | "der" | "die" | "das";
};

function stableId(de: string, level: CefrLevel): string {
  const clean = de.normalize("NFC").trim().replace(/\s+/gu, " ").toLocaleLowerCase("de");
  return createHash("sha256")
    .update(`kaps-german-v2:${level}:${clean}`)
    .digest("hex");
}

function make(raw: RawSeed): CurriculumEntry {
  const articleMatch = raw.de.match(/^(der|die|das)\s+/u);
  const article = raw.article ?? ((articleMatch?.[1] as "der" | "die" | "das" | undefined) ?? "");
  return {
    ...raw,
    id: stableId(raw.de, raw.level),
    article,
  };
}

