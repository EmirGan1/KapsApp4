import {writeFileSync} from 'node:fs';
import {MAPS} from '../src/games/kapsstrike/maps';
import {computeRoamingSpawns} from '../src/games/kapsstrike/spawns';
const data=Object.fromEntries(Object.values(MAPS).map(map=>[map.id,computeRoamingSpawns(map).map(p=>({x:+p.x.toFixed(5),y:+p.y.toFixed(5),z:+p.z.toFixed(5)}))]));
writeFileSync('src/games/kapsstrike/spawnCandidates.ts','// Generated by scripts/generate-strike-spawns.ts; validated against live collision geometry.\nexport const SPAWN_CANDIDATES = '+JSON.stringify(data)+';\n');
